type pin struct {
	commit, tree string
	files, keep  int
	lockSHA256   string
}

var upstream = pin{"5d88bfe9ef2be5a8a643166a6400eb78a30c46ec", "28d95cb57ab69df44c09167b4db7aba595188b9d", 483, 400, "35e4edc80010e386d7130c2583019514be734012fe8282cd9a9377c1930acfe0"}

type entry struct {
	Path   string `json:"path"`
	Mode   string `json:"mode"`
	Blob   string `json:"blob"`
	SHA256 string `json:"sha256"`
	Retain bool   `json:"retain"`
}
type lockFile struct {
	SchemaVersion int     `json:"schema_version"`
	Commit        string  `json:"commit"`
	Tree          string  `json:"tree"`
	Files         []entry `json:"files"`
}

var hex40 = regexp.MustCompile(`^[a-f0-9]{40}$`)
var hex64 = regexp.MustCompile(`^[a-f0-9]{64}$`)

// 與釘選版本的上游 release 排除規則一致；保留 .gitignore 及 Get.ps1。
func retained(name string) bool {
	return !strings.HasPrefix(name, ".github/") && !strings.HasPrefix(name, "Tests/") && name != "Scripts/Build-Release.ps1" && name != "Scripts/Run-Tests.ps1"
}
func validPath(name string) bool {
	if name == "" || path.Clean(name) != name || strings.HasPrefix(name, "/") || strings.ContainsAny(name, "\\:\r\n\t") {
		return false
	}
	for _, part := range strings.Split(name, "/") {
		if part == "" || part == "." || part == ".." || strings.HasSuffix(part, ".") || strings.HasSuffix(part, " ") {
			return false
		}
	}
	return true
}
func git(source string, args ...string) ([]byte, error) {
	all := append([]string{"--no-replace-objects", "-C", source}, args...)
	b, e := exec.Command("git", all...).Output()
	if e != nil {
		return nil, fmt.Errorf("git %s failed: %w", args[0], e)
	}
	return b, nil
}
func snapshot(source string, expected pin) (lockFile, map[string][]byte, error) {
	var lock lockFile
	if !hex40.MatchString(expected.commit) || !hex40.MatchString(expected.tree) {
		return lock, nil, fmt.Errorf("invalid fixed source identity")
	}
	b, e := git(source, "rev-parse", expected.commit+"^{tree}")
	if e != nil || strings.TrimSpace(string(b)) != expected.tree {
		return lock, nil, fmt.Errorf("upstream commit tree mismatch")
	}
	b, e = git(source, "ls-tree", "-r", "-z", "--full-tree", expected.commit)
	if e != nil {
		return lock, nil, e
	}
	lock = lockFile{1, expected.commit, expected.tree, []entry{}}
	contents := map[string][]byte{}
	names := map[string]bool{}
	for _, raw := range bytes.Split(b, []byte{0}) {
		if len(raw) == 0 {
			continue
		}
		row := bytes.SplitN(raw, []byte{'\t'}, 2)
		if len(row) != 2 {
			return lock, nil, fmt.Errorf("invalid git tree entry")
		}
		info := strings.Fields(string(row[0]))
		name := string(row[1])
		if len(info) != 3 || (info[0] != "100644" && info[0] != "100755") || info[1] != "blob" || !hex40.MatchString(info[2]) || !validPath(name) || names[strings.ToLower(name)] {
			return lock, nil, fmt.Errorf("invalid upstream tree path or mode")
		}
		names[strings.ToLower(name)] = true
		data, err := git(source, "cat-file", "blob", info[2])
		if err != nil {
			return lock, nil, err
		}
		h := sha256.Sum256(data)
		keep := retained(name)
		lock.Files = append(lock.Files, entry{name, info[0], info[2], fmt.Sprintf("%x", h), keep})
		if keep {
			contents[name] = data
		}
	}
	sort.Slice(lock.Files, func(i, j int) bool { return lock.Files[i].Path < lock.Files[j].Path })
	if len(lock.Files) != expected.files || len(contents) != expected.keep {
		return lock, nil, fmt.Errorf("upstream file count mismatch")
	}
	return lock, contents, nil
}
func encodeLock(lock lockFile) ([]byte, error) {
	b, e := json.MarshalIndent(lock, "", "  ")
	return append(b, '\n'), e
}
func loadLock(file string, expected pin) (lockFile, error) {
	var l lockFile
	b, e := os.ReadFile(file)
	if e != nil {
		return l, e
	}
	if !hex64.MatchString(expected.lockSHA256) || fmt.Sprintf("%x", sha256.Sum256(b)) != expected.lockSHA256 {
		return l, fmt.Errorf("lock digest differs from reviewed pin")
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.DisallowUnknownFields()
	if e = d.Decode(&l); e != nil {
		return l, e
	}
	canonical, e := encodeLock(l)
	if e != nil || !bytes.Equal(b, canonical) {
		return l, fmt.Errorf("lock must use canonical generated bytes")
	}
	if l.SchemaVersion != 1 || l.Commit != expected.commit || l.Tree != expected.tree || len(l.Files) != expected.files {
		return l, fmt.Errorf("lock source identity mismatch")
	}
	seen := map[string]bool{}
	last := ""
	kept := 0
	for _, f := range l.Files {
		if !validPath(f.Path) || f.Path <= last || seen[strings.ToLower(f.Path)] || !hex40.MatchString(f.Blob) || !hex64.MatchString(f.SHA256) || (f.Mode != "100644" && f.Mode != "100755") || f.Retain != retained(f.Path) {
			return l, fmt.Errorf("invalid lock entry")
		}
		last = f.Path
		seen[strings.ToLower(f.Path)] = true
		if f.Retain {
			kept++
		}
	}
	if kept != expected.keep {
		return l, fmt.Errorf("lock retained file count mismatch")
	}
	return l, nil
}
func safeOutput(source, dest string) bool {
	a, e := filepath.Abs(source)
	if e != nil {
		return false
	}
	a, e = filepath.EvalSymlinks(a)
	if e != nil {
		return false
	}
	b, e := filepath.Abs(dest)
	if e != nil {
		return false
	}
	parent, e := filepath.EvalSymlinks(filepath.Dir(b))
	if e != nil {
		return false
	}
	b = filepath.Join(parent, filepath.Base(b))
	rel, e := filepath.Rel(a, b)
	if e != nil {
		return filepath.VolumeName(a) != filepath.VolumeName(b)
	}
	return rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator))
}
func verify(vendor string, l lockFile) error {
	expected := map[string]entry{}
	for _, f := range l.Files {
		if f.Retain {
			expected[f.Path] = f
		}
	}
	seen := map[string]bool{}
	err := filepath.WalkDir(vendor, func(p string, d fs.DirEntry, e error) error {
		if e != nil {
			return e
		}
		if d.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("symlink is not permitted")
		}
		if d.IsDir() {
			return nil
		}
		info, e := d.Info()
		if e != nil || !info.Mode().IsRegular() {
			return fmt.Errorf("non-regular vendor file")
		}
		rel, e := filepath.Rel(vendor, p)
		if e != nil {
			return e
		}
		name := filepath.ToSlash(rel)
		f, ok := expected[name]
		if !ok || seen[name] {
			return fmt.Errorf("unexpected vendor file: %s", name)
		}
		b, e := os.ReadFile(p)
		if e != nil {
			return e
		}
		h := sha256.Sum256(b)
		if fmt.Sprintf("%x", h) != f.SHA256 {
			return fmt.Errorf("vendor hash mismatch: %s", name)
		}
		seen[name] = true
		return nil
	})
	if err != nil {
		return err
	}
	if len(seen) != len(expected) {
		return fmt.Errorf("vendor files missing")
	}
	return nil
}
func run(args []string, out io.Writer, expected pin) error {
	if len(args) == 0 {
		return fmt.Errorf("expected lock, stage, or verify")
	}
	f := flag.NewFlagSet(args[0], flag.ContinueOnError)
	f.SetOutput(io.Discard)
	source := f.String("source", "", "local upstream git repository")
	lockPath := f.String("lock", "", "generated lock")
	output := f.String("output", "", "fresh output")
	vendor := f.String("vendor", "", "vendor tree")
	if e := f.Parse(args[1:]); e != nil {
		return e
	}
	if f.NArg() != 0 {
		return fmt.Errorf("unexpected arguments")
	}
	switch args[0] {
	case "lock":
		if *source == "" || *output == "" || *lockPath != "" || *vendor != "" || !safeOutput(*source, *output) {
			return fmt.Errorf("source and fresh external lock required")
		}
		l, _, e := snapshot(*source, expected)
		if e != nil {
			return e
		}
		b, e := encodeLock(l)
		if e != nil {
			return e
		}
		file, e := os.OpenFile(*output, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if e != nil {
			return e
		}
		defer file.Close()
		if _, e = file.Write(b); e != nil {
			return e
		}
		fmt.Fprintf(out, "Locked %d upstream files.\n", len(l.Files))
		return nil
	case "stage":
		if *source == "" || *lockPath == "" || *output == "" || *vendor != "" || !safeOutput(*source, *output) {
			return fmt.Errorf("source, lock and fresh external output required")
		}
		l, e := loadLock(*lockPath, expected)
		if e != nil {
			return e
		}
		actual, data, e := snapshot(*source, expected)
		if e != nil {
			return e
		}
		if !reflect.DeepEqual(l, actual) {
			return fmt.Errorf("lock differs from fixed upstream objects")
		}
		if e = os.Mkdir(*output, 0700); e != nil {
			return e
		}
		for _, f := range l.Files {
			if !f.Retain {
				continue
			}
			p := filepath.Join(*output, filepath.FromSlash(f.Path))
			if e = os.MkdirAll(filepath.Dir(p), 0700); e != nil {
				return e
			}
			mode := fs.FileMode(0644)
			if f.Mode == "100755" {
				mode = 0755
			}
			if e = os.WriteFile(p, data[f.Path], mode); e != nil {
				return e
			}
		}
		if e = verify(*output, l); e != nil {
			return e
		}
		fmt.Fprintf(out, "Staged %d upstream files.\n", len(data))
		return nil
	case "verify":
		if *lockPath == "" || *vendor == "" || *source != "" || *output != "" {
			return fmt.Errorf("lock and vendor required")
		}
		l, e := loadLock(*lockPath, expected)
		if e != nil {
			return e
		}
		if e = verify(*vendor, l); e != nil {
			return e
		}
		fmt.Fprintln(out, "Vendor tree matches reviewed lock.")
		return nil
	default:
		return fmt.Errorf("unknown command")
	}
}
func main() {
	if e := run(os.Args[1:], os.Stdout, upstream); e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(1)
	}
}
